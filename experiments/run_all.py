"""Run every experiment, write results/results.md, and regenerate figures/*.png.

    python3 -m experiments.run_all
"""
from __future__ import annotations

import time

from .common import RES_DIR, style
from .exp_conditional import e3_conditional, e4_jackknife
from .exp_cost import e7_cost
from .exp_coverage import e1_marginal, e2_beta_law
from .exp_shift import e5_covariate_shift, e6_online


def main():
    style()
    sections = []
    steps = [
        ("E1. Marginal coverage, width and cost", lambda: e1_marginal()[0], "e1_marginal.png"),
        ("E2. Calibration-conditional coverage is Beta; PAC correction", e2_beta_law, "e2_beta_law.png"),
        ("E3. Conditional coverage under heteroscedastic noise", lambda: e3_conditional()[0], "e3_conditional.png"),
        ("E4. Jackknife vs jackknife+ as ridge becomes unstable", lambda: e4_jackknife()[0], "e4_jackknife.png"),
        ("E5. Covariate shift: weighted conformal", lambda: e5_covariate_shift()[0], "e5_covariate_shift.png"),
        ("E6. Online conformal under drift", e6_online, "e6_online.png"),
        ("E7. Cost of exactness", e7_cost, None),
    ]
    for title, fn, fig in steps:
        t0 = time.perf_counter()
        body = fn()
        dt = time.perf_counter() - t0
        print(f"{title}  ({dt:.1f}s)\n{body}\n", flush=True)
        img = f"\n\n![{title}](../figures/{fig})" if fig else ""
        sections.append(f"## {title}\n\n{body}{img}\n")
    RES_DIR.mkdir(exist_ok=True)
    header = (
        "# Results\n\nGenerated by `python3 -m experiments.run_all` (fixed seeds). All data are synthetic "
        "with a known conditional law. Coverage is computed exactly from the Gaussian CDF, not estimated "
        "from held-out samples, except in E6 (a single realized stream). Timings are Python wall-clock.\n\n"
    )
    (RES_DIR / "results.md").write_text(header + "\n".join(sections))


if __name__ == "__main__":
    main()
